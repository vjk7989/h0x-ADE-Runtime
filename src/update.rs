#[cfg(not(windows))]
fn update_requires_server_restart(
    server: &crate::api::RuntimeStatus,
    release: &ReleaseInfo,
) -> bool {
    let Some(target_generation) = release.target_endpoint_generation else {
        return true;
    };
    server
        .capabilities
        .as_ref()
        .and_then(|capabilities| capabilities.endpoint_protocol_generation)
        != Some(target_generation)
}

#[cfg(not(windows))]
fn server_supports_live_handoff(server: &crate::api::RuntimeStatus) -> bool {
    server
        .capabilities
        .as_ref()
        .is_some_and(|capabilities| capabilities.live_handoff)
}

#[cfg(not(windows))]
fn parse_stop_old_servers_after_update_response(input: &str, default_yes: bool) -> Option<bool> {
    let trimmed = input.trim().to_ascii_lowercase();
    match trimmed.as_str() {
        "" => Some(default_yes),
        "y" | "yes" => Some(true),
        "n" | "no" => Some(false),
        _ => None,
    }
}

