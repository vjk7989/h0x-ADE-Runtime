#[cfg(not(windows))]
struct DownloadedUpdate {
    current_exe: PathBuf,
    tmp_path: Option<PathBuf>,
}

#[cfg(not(windows))]
impl Drop for DownloadedUpdate {
    fn drop(&mut self) {
        if let Some(tmp_path) = self.tmp_path.take() {
            let _ = fs::remove_file(tmp_path);
        }
    }
}

/// The only hosts a release asset may be downloaded from or redirected to
/// (the same list the app and core use).
const ASSET_HOSTS: [&str; 3] = [
    "github.com",
    "objects.githubusercontent.com",
    "release-assets.githubusercontent.com",
];

/// `https://<allowed host>/...`, the host exactly: no userinfo, no port.
/// Unit tests also serve fixtures from `file://` URLs.
pub(crate) fn asset_url_allowed(url: &str) -> bool {
    #[cfg(test)]
    if url.starts_with("file://") {
        return true;
    }
    let Some(rest) = url.strip_prefix("https://") else {
        return false;
    };
    let authority = rest.split(['/', '?', '#']).next().unwrap_or_default();
    ASSET_HOSTS.contains(&authority)
}

/// Downloads `url` to `path` from an allowed host only, following at most 5
/// redirects; the URL curl landed on must be allowed too.
pub(crate) fn download_asset(url: &str, path: &Path) -> Result<(), String> {
    if !asset_url_allowed(url) {
        return Err(format!("{url}: not an https GitHub release URL"));
    }
    let output = crate::noninteractive_process::curl_command()
        .args(["-sfL", "--max-time", "120", "--max-redirs", "5"])
        .args(["--write-out", "%{url_effective}", "-o"])
        .arg(path)
        .arg(url)
        .output()
        .map_err(|e| format!("download failed: {e}"))?;
    if !output.status.success() {
        return Err("download failed".into());
    }
    let landed = String::from_utf8_lossy(&output.stdout);
    if !asset_url_allowed(landed.trim()) {
        return Err(format!("{}: redirected off GitHub", landed.trim()));
    }
    Ok(())
}

/// Download a release to a prepared executable temp file without touching the running server.
#[cfg(not(windows))]
fn download_update(release: &ReleaseInfo) -> Result<DownloadedUpdate, String> {
    let current_exe = env::current_exe().map_err(|e| format!("can't find current binary: {e}"))?;

    let parent = current_exe.parent().ok_or("can't find binary directory")?;

    // Check write permissions early
    let test_path = parent.join(".h0x-write-test");
    if let Err(e) = fs::write(&test_path, b"") {
        let _ = fs::remove_file(&test_path);
        return Err(format!(
            "install directory not writable: {} ({}). Try running with appropriate permissions.",
            parent.display(),
            e
        ));
    }
    let _ = fs::remove_file(&test_path);

    // Unique temp file (avoids races with concurrent instances)
    let tmp_path = parent.join(format!(".h0x-update-{}.tmp", std::process::id()));

    // Download the exact asset URL (pinned to the release we checked)
    if let Err(e) = download_asset(&release.download_url, &tmp_path) {
        let _ = fs::remove_file(&tmp_path);
        return Err(e);
    }

    if let Err(e) = verify_downloaded_release(&tmp_path, &release.download_url) {
        let _ = fs::remove_file(&tmp_path);
        return Err(e);
    }

    if let Some(expected) = &release.sha256 {
        if let Err(e) = crate::checksum::verify_sha256(&tmp_path, expected) {
            let _ = fs::remove_file(&tmp_path);
            return Err(format!(
                "downloaded update checksum verification failed: {e}"
            ));
        }
        tracing::info!(sha256 = %expected, "downloaded update checksum verified");
    }

    // Make executable
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        if let Err(e) = fs::set_permissions(&tmp_path, fs::Permissions::from_mode(0o755)) {
            let _ = fs::remove_file(&tmp_path);
            return Err(format!("chmod failed: {e}"));
        }
    }

    Ok(DownloadedUpdate {
        current_exe,
        tmp_path: Some(tmp_path),
    })
}

#[cfg(not(windows))]
fn install_downloaded_update(mut update: DownloadedUpdate) -> Result<(), String> {
    let tmp_path = update
        .tmp_path
        .take()
        .ok_or("downloaded update temp file is missing")?;

    // Atomic replace — rename over the current binary.
    // On Linux, the running process keeps its fd to the old inode.
    // Next launch picks up the new file.
    if let Err(e) = fs::rename(&tmp_path, &update.current_exe) {
        let _ = fs::remove_file(&tmp_path);
        return Err(format!("failed to replace binary: {e}"));
    }

    Ok(())
}

pub(crate) const WINDOWS_INSTALLER: &str = include_str!("../distribution/install.ps1");

#[cfg(windows)]
struct DownloadedWindowsUpdate {
    package_path: PathBuf,
    installer_path: PathBuf,
}

#[cfg(windows)]
impl Drop for DownloadedWindowsUpdate {
    fn drop(&mut self) {
        let _ = fs::remove_file(&self.package_path);
        let _ = fs::remove_file(&self.installer_path);
    }
}

#[cfg(windows)]
fn download_windows_update(release: &ReleaseInfo) -> Result<DownloadedWindowsUpdate, String> {
    let expected_sha256 = release
        .sha256
        .as_deref()
        .ok_or("Windows update asset is missing a SHA-256 checksum")?;
    let stem = format!("h0x-update-{}", std::process::id());
    let update = DownloadedWindowsUpdate {
        package_path: env::temp_dir().join(format!("{stem}.{}", release.package_format)),
        installer_path: env::temp_dir().join(format!("{stem}.ps1")),
    };
    fs::write(&update.installer_path, WINDOWS_INSTALLER)
        .map_err(|err| format!("failed to prepare Windows installer: {err}"))?;

    download_asset(&release.download_url, &update.package_path)?;
    // A refused package is deleted when `update` drops.
    verify_downloaded_release(&update.package_path, &release.download_url)?;
    crate::checksum::verify_sha256(&update.package_path, expected_sha256)
        .map_err(|err| format!("downloaded update checksum verification failed: {err}"))?;
    tracing::info!(sha256 = %expected_sha256, "downloaded update checksum verified");

    Ok(update)
}

#[cfg(windows)]
fn install_windows_update_with_installer(
    release: &ReleaseInfo,
    update: &DownloadedWindowsUpdate,
) -> Result<(), String> {
    let expected_sha256 = release
        .sha256
        .as_deref()
        .ok_or("Windows update asset is missing a SHA-256 checksum")?;
    let mut command = Command::new("powershell");
    command
        .args(["-NoProfile", "-ExecutionPolicy", "Bypass", "-File"])
        .arg(&update.installer_path)
        .arg("-LocalPackagePath")
        .arg(&update.package_path)
        .args([
            "-LocalPackageFormat",
            &release.package_format,
            "-LocalPackageIdentity",
            release.label(),
            "-LocalPackageSha256",
            expected_sha256,
        ])
        // Drop any inherited PSModulePath. When h0x is launched from
        // PowerShell 7, its Core module paths come first and Windows
        // PowerShell 5.1 (this `powershell`) fails to autoload cmdlets like
        // Get-FileHash. Removing it lets 5.1 compute its own default path.
        // See PowerShell/PowerShell#8635.
        .env_remove("PSModulePath");
    let status = command
        .status()
        .map_err(|err| format!("failed to run Windows installer: {err}"))?;

    if !status.success() {
        return Err(format!("Windows installer failed with status {status}"));
    }

    Ok(())
}

#[cfg(windows)]
fn windows_installed_h0x_exe_path() -> Result<PathBuf, String> {
    if let Some(install_dir) = env::var_os("H0X_INSTALL_DIR").filter(|value| !value.is_empty()) {
        return Ok(PathBuf::from(install_dir).join("h0x.exe"));
    }

    let local_app_data = env::var_os("LOCALAPPDATA")
        .ok_or("LOCALAPPDATA is not set; cannot locate HyperOx install")?;
    Ok(PathBuf::from(local_app_data)
        .join("Programs")
        .join("HyperOx")
        .join("bin")
        .join("h0x.exe"))
}

