/// Manual self-update command (`h0x update`).
pub fn self_update(options: SelfUpdateOptions) -> Result<Version, String> {
    if is_nix_managed_install() {
        return Err(
            "self-update is disabled for Nix installs; update with `nix profile upgrade` or update the flake input that provides HyperOx".into(),
        );
    }

    if running_inside_h0x() {
        return Err("run `h0x update` outside h0x after detaching from the session".into());
    }

    eprintln!("checking for updates...");

    let current = Version::current();

    let release = match check_latest()? {
        Some(r) => r,
        None => {
            eprintln!("already up to date ({})", crate::build_info::version());
            return Ok(current);
        }
    };

    if let Err(e) = crate::release_notes::save_pending(release.label(), &release.notes_body) {
        tracing::warn!("failed to save pending release notes: {e}");
    }

    #[cfg(windows)]
    {
        let _ = options;

        eprintln!(
            "installing {} with the Windows installer...",
            release.label()
        );
        if let Some(sha256) = &release.sha256 {
            tracing::debug!(sha256 = %sha256, "selected Windows update asset has checksum");
        }
        eprintln!("downloading {}...", release.label());
        let downloaded_update = download_windows_update(&release)?;
        eprintln!("downloaded {}", release.label());
        install_windows_update_with_installer(&release, &downloaded_update)?;
        let updated_exe = windows_installed_h0x_exe_path()?;
        eprintln!("installed {}", release.label());
        print_outdated_integration_notice_with_updated_binary(&updated_exe);
        eprintln!(
            "Open a new terminal, or reconnect SSH, then start h0x again to use the updated client. Running servers remain active; restart them later only if you need server-side changes from {}.",
            release.label()
        );
        print_saved_machine_update_notice();
    }

    #[cfg(not(windows))]
    {
        let running_server_plans = plan_running_server_updates(&release)?;
        let server_update_decisions =
            confirm_running_server_update_action(running_server_plans, &release, options)?;

        eprintln!("downloading {}...", release.label());
        let downloaded_update = download_update(&release)?;
        let updated_exe = downloaded_update.current_exe.clone();
        eprintln!("downloaded {}", release.label());
        if !options.live_handoff
            && !prompt_to_complete_plain_update(&server_update_decisions, &release)?
        {
            eprintln!("HyperOx was not updated.");
            eprintln!("Stop running HyperOx sessions when ready, then run `h0x update` again.");
            return Ok(current);
        }
        install_downloaded_update(downloaded_update)?;
        eprintln!("installed {}", release.label());
        let server_update_decisions = if options.live_handoff {
            server_update_decisions
        } else {
            mark_plain_update_stop_decisions(server_update_decisions)
        };
        let server_update_outcomes = apply_running_session_update_decisions(
            &release,
            &updated_exe,
            server_update_decisions,
        )?;
        print_outdated_integration_notice_with_updated_binary(&updated_exe);

        print_running_session_update_outcomes(&server_update_outcomes, &release);
        print_saved_machine_update_notice();
    }

    Ok(release.version)
}

fn print_saved_machine_update_notice() {
    let profiles = match crate::client::endpoint::EndpointCatalog::load_profiles() {
        Ok(profiles) => profiles,
        Err(error) => {
            tracing::debug!(%error, "skipping saved machine update notice");
            return;
        }
    };
    for line in saved_machine_update_notice_lines(&profiles) {
        eprintln!("{line}");
    }
}

fn saved_machine_update_notice_lines(
    profiles: &[crate::client::endpoint::SavedSshEndpoint],
) -> Vec<String> {
    let mut targets: Vec<&str> = Vec::new();
    let mut labels: Vec<&str> = Vec::new();
    for profile in profiles.iter().filter(|profile| profile.enabled) {
        if !targets.contains(&profile.target.as_str()) {
            targets.push(&profile.target);
            labels.push(&profile.label);
        }
    }
    if labels.is_empty() {
        return Vec::new();
    }
    let mut lines = vec![
        String::new(),
        "your SSH machines run their own h0x and may be older:".to_string(),
    ];
    lines.extend(labels.into_iter().map(|label| format!("  {label}")));
    lines.push("run `h0x update` on each one. it will tell you what to restart there.".to_string());
    lines
}

#[cfg(not(windows))]
struct KeptServer<'a> {
    label: &'a str,
    version: &'a str,
    stop_command: &'a str,
    attach_command: Option<&'a str>,
}

#[cfg(not(windows))]
impl KeptServer<'_> {
    fn reconnect(&self) -> String {
        match self.attach_command {
            Some(attach) => format!("`{attach}`"),
            None => "h0x with the same socket override".to_string(),
        }
    }
}

#[cfg(not(windows))]
fn kept_server_notice_lines(kept: &[KeptServer<'_>], release_label: &str) -> Vec<String> {
    match kept {
        [] => Vec::new(),
        [server] => vec![
            String::new(),
            format!(
                "your running server is still v{}. run {} to reconnect; everything keeps working.",
                server.version,
                server.reconnect()
            ),
            format!("server fixes in v{release_label} apply only after it restarts."),
            format!(
                "when your agents are idle, run `{}`, then {}.",
                server.stop_command,
                server.reconnect()
            ),
            "this closes running panes and their agents.".to_string(),
        ],
        servers => {
            let width = servers
                .iter()
                .map(|server| server.label.chars().count())
                .max()
                .unwrap_or(0);
            let mut lines = vec![
                String::new(),
                "your running servers are still older. reconnect as usual; everything keeps working."
                    .to_string(),
                format!("server fixes in v{release_label} apply only after each one restarts:"),
            ];
            lines.extend(servers.iter().map(|server| {
                format!(
                    "  {:<width$}  v{}  `{}`, then {}",
                    server.label,
                    server.version,
                    server.stop_command,
                    server.reconnect()
                )
            }));
            lines.push(
                "restart one when its agents are idle. this closes its panes and their agents."
                    .to_string(),
            );
            lines
        }
    }
}

fn print_outdated_integration_notice_with_updated_binary(updated_exe: &Path) {
    let status = Command::new(updated_exe)
        .args(["integration", "status", "--outdated-only"])
        .status();

    if !status.is_ok_and(|status| status.success()) {
        crate::integration::print_outdated_update_notice();
    }
}

/// Background update check: only surface availability and release notes.
/// Runs in a background thread at startup.
pub fn auto_update(events: tokio::sync::mpsc::Sender<crate::events::AppEvent>) {
    crate::logging::update_check_started();
    if let Ok(version) = env::var(FAKE_UPDATE_VERSION_ENV) {
        let version = version.trim();
        if !version.is_empty() {
            tracing::info!(
                env = FAKE_UPDATE_VERSION_ENV,
                version,
                "using fake update version for local testing"
            );
            if let Err(e) =
                crate::release_notes::save_pending(version, &fake_release_notes_body(version))
            {
                tracing::warn!("failed to save fake pending release notes: {e}");
            }
            let _ = events.blocking_send(crate::events::AppEvent::UpdateReady {
                version: version.to_string(),
                install_command: update_install_command().to_string(),
            });
        }
        return;
    }

    let release = match check_latest() {
        Ok(Some(r)) => r,
        Ok(None) => return,
        Err(err) => {
            crate::logging::update_check_failed(&err);
            return;
        }
    };

    crate::logging::update_available(release.label());
    tracing::info!("new build available at {}", release.download_url);

    if let Err(e) = crate::release_notes::save_pending(release.label(), &release.notes_body) {
        tracing::warn!("failed to save pending release notes: {e}");
    }

    tracing::info!(
        "auto-update check: {} available, waiting for explicit install",
        release.label()
    );

    // Notify the TUI — blocking_send is safe from a std::thread
    let _ = events.blocking_send(crate::events::AppEvent::UpdateReady {
        version: release.label().to_string(),
        install_command: update_install_command().to_string(),
    });
}

