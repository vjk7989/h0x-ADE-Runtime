/// Information about an available update.
#[derive(Debug, Clone)]
struct ReleaseInfo {
    version: Version,
    identity: String,
    #[cfg(not(windows))]
    target_protocol: Option<u32>,
    #[cfg(not(windows))]
    target_endpoint_generation: Option<u32>,
    download_url: String,
    sha256: Option<String>,
    #[cfg(windows)]
    package_format: String,
    notes_body: String,
}

impl ReleaseInfo {
    fn label(&self) -> &str {
        &self.identity
    }
}

fn fetch_update_manifest() -> Result<UpdateManifest, String> {
    fetch_json_manifest(UPDATE_MANIFEST_URL)
}

fn fetch_json_manifest<T>(url: &str) -> Result<T, String>
where
    T: serde::de::DeserializeOwned,
{
    let output = crate::noninteractive_process::curl_command()
        .args([
            "-sfL",
            "--retry",
            "3",
            "--connect-timeout",
            "10",
            "--max-time",
            "20",
            url,
        ])
        .output()
        .map_err(|e| format!("curl failed: {e}"))?;

    if !output.status.success() {
        return Err("failed to fetch update manifest".into());
    }
    verify_release_signature(
        "the update manifest",
        url.rsplit('/').next().unwrap_or(url),
        &output.stdout,
        fetch_release_signature(url).as_deref(),
        RELEASE_PUBLIC_KEY,
    )?;

    serde_json::from_slice(&output.stdout)
        .map_err(|e| format!("failed to parse update manifest JSON: {e}"))
}

/// Downloads `<url>.minisig`; `None` when it does not download.
pub(crate) fn fetch_release_signature(url: &str) -> Option<String> {
    let output = crate::noninteractive_process::curl_command()
        .args([
            "-sfL",
            "--retry",
            "3",
            "--connect-timeout",
            "10",
            "--max-time",
            "20",
        ])
        .arg(format!("{url}.minisig"))
        .output()
        .ok()?;
    output
        .status
        .success()
        .then(|| String::from_utf8_lossy(&output.stdout).into_owned())
}

/// Checks `bytes` against its minisign `signature` by `key`, made for the
/// release asset `file` (its trusted comment's `file:`, so one signed file
/// cannot stand in for another).
pub(crate) fn verify_release_signature(
    name: &str,
    file: &str,
    bytes: &[u8],
    signature: Option<&str>,
    key: &str,
) -> Result<(), String> {
    let checked = (|| {
        let key = minisign_verify::PublicKey::from_base64(key).map_err(|e| e.to_string())?;
        let text = signature.ok_or("it has no signature")?;
        let signature = minisign_verify::Signature::decode(text)
            .map_err(|e| format!("its signature is unreadable: {e}"))?;
        key.verify(bytes, &signature, false)
            .map_err(|e| format!("its signature does not match: {e}"))?;
        let file_field = format!("file:{file}");
        if signature
            .trusted_comment()
            .split('\t')
            .any(|f| f == file_field)
        {
            Ok(())
        } else {
            Err(format!("its signature is for another file, not {file}"))
        }
    })();
    checked.map_err(|why| format!("{name} is not signed by the h0x release key: {why}"))
}

/// Checks a downloaded release asset at `path` against `<url>.minisig`.
pub(crate) fn verify_downloaded_release(path: &Path, url: &str) -> Result<(), String> {
    let bytes = fs::read(path).map_err(|e| format!("failed to read downloaded update: {e}"))?;
    verify_release_signature(
        "the downloaded update",
        url.rsplit('/').next().unwrap_or(url),
        &bytes,
        fetch_release_signature(url).as_deref(),
        RELEASE_PUBLIC_KEY,
    )
}

fn handle_manifest_announcement(version: &str, value: Option<&serde_json::Value>) {
    let announcement = match value {
        Some(value) => match serde_json::from_value::<
            crate::product_announcements::ManifestAnnouncement,
        >(value.clone())
        {
            Ok(announcement) => Some(announcement),
            Err(err) => {
                tracing::warn!("skipping invalid product announcement in update manifest: {err}");
                None
            }
        },
        None => None,
    };

    if let Err(err) =
        crate::product_announcements::save_manifest_announcement(version, announcement.as_ref())
    {
        tracing::warn!("failed to save product announcement: {err}");
    }
}

fn release_info_from_manifest(
    manifest: &UpdateManifest,
    current: &Version,
) -> Result<Option<ReleaseInfo>, String> {
    let latest = Version::parse(&manifest.version)
        .ok_or_else(|| format!("invalid version in update manifest: {}", manifest.version))?;

    if latest <= *current {
        return Ok(None); // up to date
    }

    let metadata = manifest
        .metadata_for_version(&latest)
        .ok_or_else(|| format!("missing release metadata for v{latest}"))?;
    let notes_body = metadata.notes_body();
    if notes_body.is_empty() {
        return Err("update manifest notes are empty".into());
    }

    let (os, arch) = platform_target();
    let asset_key = format!("{os}-{arch}");
    let asset = manifest
        .assets
        .get(&asset_key)
        .ok_or_else(|| format!("no binary for {asset_key} in update manifest"))?;
    let download_url = asset.url.clone();
    let sha256 = asset
        .sha256
        .clone()
        .or_else(|| manifest.sha256.get(&asset_key).cloned())
        .ok_or_else(|| {
            format!("update manifest asset {asset_key} is missing a SHA-256 checksum")
        })?;

    Ok(Some(ReleaseInfo {
        identity: latest.to_string(),
        version: latest,
        #[cfg(not(windows))]
        target_protocol: manifest.protocol,
        #[cfg(not(windows))]
        target_endpoint_generation: manifest.endpoint_generation,
        download_url,
        sha256: Some(sha256),
        #[cfg(windows)]
        package_format: asset.package_format()?,
        notes_body,
    }))
}

/// Check the hosted update manifest for the latest release. Returns release info if newer.
fn check_latest() -> Result<Option<ReleaseInfo>, String> {
    let manifest = fetch_update_manifest()?;
    let release = release_info_from_manifest(&manifest, &Version::current())?;
    if let Some(release) = release.as_ref() {
        if let Some(metadata) = manifest.metadata_for_version(&release.version) {
            handle_manifest_announcement(
                &release.version.to_string(),
                metadata.announcement.as_ref(),
            );
        }
    }
    Ok(release)
}

